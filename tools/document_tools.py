"""Listing-document ingestion and report export tools.

Reads real ``.docx`` and ``.txt`` listing sheets from disk, extracts
structured property fields with deterministic regex heuristics, and can
export a formatted ``.docx`` property report. No network access.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict

from mcp.server.mcpserver import MCPServer

from utils import audit

_PROPERTY_TYPES = [
    "single family home",
    "single-family home",
    "townhouse",
    "condo",
    "condominium",
    "duplex",
    "multi-family",
    "apartment",
    "villa",
    "bungalow",
    "cottage",
    "loft",
]


def read_listing_text(file_path: str) -> str:
    """Read a ``.docx`` or ``.txt`` file and return its plain text."""

    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")

    suffix = path.suffix.lower()
    if suffix == ".txt":
        return path.read_text(encoding="utf-8")
    if suffix == ".docx":
        from docx import Document

        document = Document(str(path))
        paragraphs = [p.text.strip() for p in document.paragraphs if p.text.strip()]
        return "\n".join(paragraphs)

    raise ValueError(
        f"Unsupported file format '{suffix}'. Supported formats: .docx, .txt"
    )


def _to_number(raw: str) -> float:
    return float(raw.replace(",", "").replace("$", "").strip())


def extract_listing_fields(text: str) -> Dict[str, Any]:
    """Extract structured property fields from free-form listing text."""

    lowered = text.lower()
    fields: Dict[str, Any] = {
        "price": None,
        "bedrooms": None,
        "bathrooms": None,
        "square_feet": None,
        "year_built": None,
        "property_type": None,
        "address": None,
    }

    price_match = re.search(r"\$\s*([\d,]+(?:\.\d+)?)", text)
    if price_match:
        try:
            fields["price"] = _to_number(price_match.group(1))
        except ValueError:
            pass

    bed_match = re.search(r"(\d+(?:\.\d+)?)\s*(?:bed|bedroom|br\b)", lowered)
    if bed_match:
        fields["bedrooms"] = float(bed_match.group(1))

    bath_match = re.search(r"(\d+(?:\.\d+)?)\s*(?:bath|bathroom|ba\b)", lowered)
    if bath_match:
        fields["bathrooms"] = float(bath_match.group(1))

    sqft_match = re.search(r"([\d,]+)\s*(?:sq\.?\s*ft|square\s*feet|sqft)", lowered)
    if sqft_match:
        try:
            fields["square_feet"] = int(_to_number(sqft_match.group(1)))
        except ValueError:
            pass

    year_match = re.search(
        r"(?:built|year built|constructed)[^\d]{0,10}(\d{4})", lowered
    )
    if year_match:
        fields["year_built"] = int(year_match.group(1))

    for ptype in _PROPERTY_TYPES:
        if ptype in lowered:
            fields["property_type"] = ptype.title()
            break

    addr_match = re.search(
        r"(?:address|located at|property at)\s*:?\s*(.+)", text, re.IGNORECASE
    )
    if addr_match:
        fields["address"] = addr_match.group(1).splitlines()[0].strip()

    return fields


def _build_property_report_docx(report: Dict[str, Any], output_path: Path) -> None:
    from docx import Document

    document = Document()
    document.add_heading("Property Report", level=0)
    document.add_paragraph(
        "Automated property summary generated by the Real Estate MCP Server. "
        "Analytical estimate only; not a certified appraisal."
    )

    address = report.get("address") or report.get("property_id") or "Property"
    document.add_heading(str(address), level=1)

    field_labels = [
        ("price", "List Price"),
        ("estimated_value", "Estimated Value"),
        ("bedrooms", "Bedrooms"),
        ("bathrooms", "Bathrooms"),
        ("square_feet", "Square Feet"),
        ("year_built", "Year Built"),
        ("property_type", "Property Type"),
        ("area", "Area"),
    ]
    table = document.add_table(rows=1, cols=2)
    header = table.rows[0].cells
    header[0].text = "Field"
    header[1].text = "Value"
    for key, label in field_labels:
        if report.get(key) is not None:
            row = table.add_row().cells
            row[0].text = label
            row[1].text = str(report.get(key))

    if report.get("notes"):
        document.add_heading("Notes", level=1)
        document.add_paragraph(str(report["notes"]))

    document.add_heading("Disclaimer", level=1)
    document.add_paragraph(
        "Generated by Real Estate MCP Server. Verify all figures independently "
        "before relying on this report."
    )
    document.save(str(output_path))


def register_document_tools(mcp: MCPServer) -> None:
    """Register listing-document ingestion and export tools."""

    @mcp.tool()
    def ingest_listing_document(file_path: str) -> str:
        """Read a ``.docx``/``.txt`` listing sheet and extract property fields."""
        audit("ingest_listing_document", file_path=file_path)
        try:
            text = read_listing_text(file_path)
        except FileNotFoundError:
            return json.dumps(
                {"file_path": file_path, "error": "File not found."}, indent=2
            )
        except ValueError as exc:
            return json.dumps({"file_path": file_path, "error": str(exc)}, indent=2)
        fields = extract_listing_fields(text)
        return json.dumps(
            {
                "file_path": file_path,
                "title": Path(file_path).name,
                "extracted_fields": fields,
                "notice": "Automated extraction; verify against source listing.",
            },
            indent=2,
        )

    @mcp.tool()
    def compare_listing_documents(file_path_a: str, file_path_b: str) -> str:
        """Extract fields from two listing documents and compare them."""
        audit(
            "compare_listing_documents",
            file_path_a=file_path_a,
            file_path_b=file_path_b,
        )
        try:
            fields_a = extract_listing_fields(read_listing_text(file_path_a))
            fields_b = extract_listing_fields(read_listing_text(file_path_b))
        except FileNotFoundError as exc:
            return json.dumps(
                {"error": "File not found.", "detail": str(exc)}, indent=2
            )
        except ValueError as exc:
            return json.dumps({"error": str(exc)}, indent=2)

        differences = {
            key: {"document_a": fields_a.get(key), "document_b": fields_b.get(key)}
            for key in fields_a
            if fields_a.get(key) != fields_b.get(key)
        }
        return json.dumps(
            {
                "document_a": Path(file_path_a).name,
                "document_b": Path(file_path_b).name,
                "difference_count": len(differences),
                "differences": differences,
            },
            indent=2,
        )

    @mcp.tool()
    def export_property_report(report_json: str, output_path: str) -> str:
        """Generate a ``.docx`` property report from a JSON report object.

        The JSON may come from ``ingest_listing_document``,
        ``estimate_property_value``, or ``get_property_details``.
        """
        audit("export_property_report", output_path=output_path)
        try:
            report = json.loads(report_json)
        except json.JSONDecodeError as exc:
            return json.dumps(
                {"error": "Invalid report JSON.", "detail": str(exc)}, indent=2
            )
        if isinstance(report.get("extracted_fields"), dict):
            merged: Dict[str, Any] = dict(report["extracted_fields"])
            merged.update({k: v for k, v in report.items() if k != "extracted_fields"})
            report = merged

        destination = Path(output_path)
        if destination.suffix.lower() != ".docx":
            return json.dumps({"error": "Output path must end with .docx"}, indent=2)
        destination.parent.mkdir(parents=True, exist_ok=True)
        _build_property_report_docx(report, destination)
        return json.dumps(
            {
                "output_path": str(destination),
                "message": "Property report exported successfully.",
            },
            indent=2,
        )
